#!/usr/bin/env node
/** Generate invoke channel unions, per-channel contracts, and window.taskweaver from the IPC table. */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { IPC_CHANNELS, OPTIONAL_BRIDGE_NAMESPACES } from '../electron/ipc/channels.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const orderedChannels = [...IPC_CHANNELS].sort((left, right) => (
  left.name < right.name ? -1 : left.name > right.name ? 1 : 0
))
const tsString = (value) => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`

function assertTable() {
  const seenNames = new Set()
  const seenPaths = new Set()
  for (const entry of orderedChannels) {
    if (!entry || typeof entry.name !== 'string' || !entry.name) throw new Error('IPC table contains an entry without a channel name')
    if (seenNames.has(entry.name)) throw new Error(`IPC table contains duplicate channel: ${entry.name}`)
    seenNames.add(entry.name)
    if (entry.direction !== 'renderer-to-main/invoke') throw new Error(`${entry.name}: unsupported direction ${entry.direction}`)
    if (!entry.handlerModule || !entry.bridgePath) throw new Error(`${entry.name}: handlerModule and bridgePath are required`)
    if (entry.argsSchema?.kind !== 'typescript' || !entry.argsSchema.reference) throw new Error(`${entry.name}: missing argsSchema type reference`)
    if (entry.resultSchema?.kind !== 'typescript' || !entry.resultSchema.reference) throw new Error(`${entry.name}: missing resultSchema type reference`)
    const argsType = entry.argsSchema.reference.match(/^Parameters<NonNullable<(.+)>>$/)?.[1]
    if (!argsType || entry.resultSchema.reference !== `Awaited<ReturnType<NonNullable<${argsType}>>>`) {
      throw new Error(`${entry.name}: argsSchema and resultSchema must reference the same API method`)
    }
    if (seenPaths.has(entry.bridgePath)) throw new Error(`multiple invoke channels map to the same preload method: ${entry.bridgePath}`)
    seenPaths.add(entry.bridgePath)
  }
}

function renderInvokeChannels() {
  const lines = [
    '// AUTO-GENERATED by scripts/gen-ipc-types.mjs — 勿手改。',
    '',
    '/** 主进程 ipcHandle 与 preload invoke 通道（与 electron/ipc/channels.mjs 一致）。 */',
    'export type InvokeChannel =',
    ...orderedChannels.map(({ name }) => `  | ${tsString(name)}`),
    '',
    'export const INVOKE_CHANNELS: readonly InvokeChannel[] = [',
    ...orderedChannels.map(({ name }) => `  ${tsString(name)},`),
    ']',
    '',
  ]
  return lines.join('\n')
}

function renderChannelContracts() {
  const lines = [
    '// AUTO-GENERATED by scripts/gen-ipc-types.mjs — 勿手改。',
    '',
    '/** Type-level view of each invoke route, derived from electron/ipc/channels.mjs. */',
    'export interface IpcChannelContracts {',
  ]
  for (const entry of orderedChannels) {
    lines.push(`  ${tsString(entry.name)}: { readonly args: ${entry.argsSchema.reference}; readonly result: ${entry.resultSchema.reference} }`)
  }
  lines.push(
    '}',
    '',
    'export type IpcInvokeChannel = keyof IpcChannelContracts',
    'export type IpcInvokeArgs<Channel extends IpcInvokeChannel> = IpcChannelContracts[Channel][\'args\']',
    'export type IpcInvokeResult<Channel extends IpcInvokeChannel> = IpcChannelContracts[Channel][\'result\']',
    '',
  )
  return lines.join('\n')
}

function renderBridgeType() {
  const namespaces = new Map()
  const rootMethods = new Map()
  for (const entry of orderedChannels) {
    const parts = entry.bridgePath.split('.')
    const typeReference = entry.argsSchema.reference.match(/^Parameters<NonNullable<(.+)>>$/)?.[1]
    const typeMatch = typeReference?.match(/^import\('([^']+)'\)\.([A-Za-z0-9_]+)\['([A-Za-z0-9_]+)'\]$/)
    if (!typeMatch) throw new Error(`${entry.name}: cannot derive bridge type from ${entry.argsSchema.reference}`)
    const [, moduleName, interfaceName, methodName] = typeMatch
    const rootName = parts[0]
    if (parts.length === 1) {
      rootMethods.set(rootName, `import('${moduleName}').${interfaceName}['${methodName}']`)
      continue
    }
    const previous = namespaces.get(rootName)
    const descriptor = { moduleName, interfaceName }
    if (previous && (previous.moduleName !== moduleName || previous.interfaceName !== interfaceName)) {
      throw new Error(`${entry.name}: inconsistent bridge API type for namespace ${rootName}`)
    }
    namespaces.set(rootName, descriptor)
  }

  const fields = []
  for (const [name, typeReference] of rootMethods) fields.push({ name, typeReference })
  for (const [name, { moduleName, interfaceName }] of namespaces) {
    fields.push({ name, typeReference: `import('${moduleName}').${interfaceName}` })
  }
  fields.sort((a, b) => a.name.localeCompare(b.name))

  const optional = new Set(OPTIONAL_BRIDGE_NAMESPACES)
  const lines = [
    '// AUTO-GENERATED by scripts/gen-ipc-types.mjs — 勿手改。',
    '',
    '/** window.taskweaver is derived from the channel table and current API method contracts. */',
    'export interface TaskweaverBridge {',
  ]
  for (const field of fields) {
    lines.push(`  ${field.name}${optional.has(field.name) ? '?' : ''}: ${field.typeReference}`)
  }
  lines.push(
    '}',
    '',
    'declare global {',
    '  interface Window {',
    '    taskweaver?: TaskweaverBridge',
    '  }',
    '}',
    '',
    'export {}',
    '',
  )
  return lines.join('\n')
}

export function renderGeneratedIpcTypes() {
  assertTable()
  return new Map([
    [path.join(root, 'src/shared/ipc-invoke-channels.ts'), renderInvokeChannels()],
    [path.join(root, 'src/shared/ipc-channel-contracts.generated.ts'), renderChannelContracts()],
    [path.join(root, 'src/shared/ipc-bridge.generated.d.ts'), renderBridgeType()],
  ])
}

export function checkGeneratedIpcTypes() {
  let stale = false
  for (const [filePath, expected] of renderGeneratedIpcTypes()) {
    const actual = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null
    if (actual !== expected) {
      console.error(`gen-ipc-types: stale generated file: ${path.relative(root, filePath)}`)
      stale = true
    }
  }
  return !stale
}

function writeGeneratedIpcTypes() {
  let changed = false
  for (const [filePath, expected] of renderGeneratedIpcTypes()) {
    const actual = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null
    if (actual === expected) continue
    fs.writeFileSync(filePath, expected)
    console.log(`gen-ipc-types: wrote ${path.relative(root, filePath)}`)
    changed = true
  }
  if (!changed) console.log('gen-ipc-types: generated IPC types already up to date')
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : ''
if (invokedPath === fileURLToPath(import.meta.url)) {
  assertTable()
  if (process.argv.includes('--check')) {
    if (!checkGeneratedIpcTypes()) process.exitCode = 1
  } else {
    writeGeneratedIpcTypes()
  }
}
