#!/usr/bin/env node
/** Generate renderer HTTP bridge for native shells (Swift / future WebView2). */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { IPC_CHANNELS, PRELOAD_EVENTS, PRELOAD_LOCAL_METHODS } from '../contract/channels.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outPath = path.join(root, 'src/shell/taskweaver-shell-bridge.generated.ts')

function setBridgeMethod(tree, bridgePath, source) {
  const segments = bridgePath.split('.')
  let current = tree
  for (const segment of segments.slice(0, -1)) {
    if (current[segment] === undefined) current[segment] = {}
    current = current[segment]
  }
  current[segments.at(-1)] = source
}

function renderObject(tree, indent = 2) {
  const pad = ' '.repeat(indent)
  const childPad = ' '.repeat(indent + 2)
  const lines = Object.entries(tree).map(([key, value]) => {
    const rendered = typeof value === 'string' ? value : renderObject(value, indent + 2)
    return `${childPad}${key}: ${rendered}`
  })
  return `{\n${lines.join(',\n')}\n${pad}}`
}

function renderShellBridge() {
  const tree = {}
  for (const entry of IPC_CHANNELS) {
    setBridgeMethod(tree, entry.bridgePath, `(...args: unknown[]) => invoke(${JSON.stringify(entry.name)}, ...args)`)
  }
  for (const entry of PRELOAD_EVENTS) {
    const sub = `(listener: (payload: unknown) => void) => subscribe(${JSON.stringify(entry.event)}, listener)`
    setBridgeMethod(tree, entry.bridgePath, sub)
  }
  for (const entry of PRELOAD_LOCAL_METHODS) {
    if (entry.bridgePath === 'workspace.getDroppedFilePath') {
      setBridgeMethod(tree, entry.bridgePath, '(_file: File) => ""')
      continue
    }
    setBridgeMethod(tree, entry.bridgePath, '() => undefined')
  }

  return `// AUTO-GENERATED by scripts/gen-shell-bridge.mjs — 勿手改。\n\nimport type { TaskweaverBridge } from '../shared/ipc-bridge.generated'\n\nlet eventController: AbortController | null = null\nlet shellApiToken: string | null = null\nconst channelListeners = new Map<string, Set<(payload: unknown) => void>>()\n\nfunction shellApiHeaders() {
  const headers: Record<string, string> = { Accept: 'text/event-stream' }
  if (shellApiToken) headers['X-TaskWeaver-Shell-Token'] = shellApiToken
  return headers
}

function dispatchShellEvent(data: string) {
  try {
    const parsed = JSON.parse(data) as { channel?: string; payload?: unknown }
    if (!parsed.channel) return
    const listeners = channelListeners.get(parsed.channel)
    if (!listeners) return
    for (const listener of listeners) {
      try { listener(parsed.payload) } catch { /* isolate subscribers */ }
    }
  } catch {
    /* ignore malformed push */
  }
}

function waitForReconnect(ms: number, signal: AbortSignal) {
  return new Promise<void>((resolve) => {
    if (signal.aborted) return resolve()
    const finish = () => {
      clearTimeout(timer)
      signal.removeEventListener('abort', finish)
      resolve()
    }
    const timer = setTimeout(finish, ms)
    signal.addEventListener('abort', finish, { once: true })
  })
}

async function pumpEvents(apiBase: string, signal: AbortSignal) {
  let retryDelay = 500
  while (!signal.aborted) {
    try {
      const response = await fetch(apiBase + '/shell/v1/events', {
        headers: shellApiHeaders(),
        signal,
      })
      if (response.status === 401 || response.status === 403) return\n      if (!response.ok || !response.body) throw new Error('Shell event stream unavailable')
      retryDelay = 500
      const reader = response.body.getReader()
      const decoder = new TextDecoder()
      let buffer = ''
      while (!signal.aborted) {
        const { value, done } = await reader.read()
        if (done) break
        buffer += decoder.decode(value, { stream: true })
        let separator = buffer.indexOf('\\n\\n')
        while (separator !== -1) {
          const frame = buffer.slice(0, separator)
          buffer = buffer.slice(separator + 2)
          const data = frame.split('\\n')
            .filter((line) => line.startsWith('data:'))
            .map((line) => line.slice(5).replace(/^ /, ''))
          if (data.length) dispatchShellEvent(data.join('\\n'))
          separator = buffer.indexOf('\\n\\n')
        }
      }
      try { await reader.cancel() } catch { /* stream already closed */ }
    } catch {
      if (signal.aborted) return
    }
    await waitForReconnect(retryDelay, signal)
    retryDelay = Math.min(retryDelay * 2, 10_000)
  }
}

function ensureEventStream(apiBase: string) {
  if (eventController) return
  const controller = new AbortController()
  eventController = controller
  void pumpEvents(apiBase, controller.signal).finally(() => {
    if (eventController === controller) eventController = null
  })
}\n\nfunction subscribe(channel: string, listener: (payload: unknown) => void) {\n  const apiBase = getShellApiBase()\n  ensureEventStream(apiBase)\n  let set = channelListeners.get(channel)\n  if (!set) {\n    set = new Set()\n    channelListeners.set(channel, set)\n  }\n  set.add(listener)\n  return () => {\n    set?.delete(listener)\n  }\n}\n\nlet shellApiBase: string | null = null\n\nexport function setShellApiBase(base: string) {\n  const normalized = base.replace(/\\/$/, '')\n  if (shellApiBase !== normalized) {\n    eventController?.abort()\n    eventController = null\n  }\n  shellApiBase = normalized\n}\n\nexport function setShellApiToken(token: string) {\n  if (shellApiToken !== token) {\n    eventController?.abort()\n    eventController = null\n  }\n  shellApiToken = token\n}\n\nexport function getShellApiBase() {\n  if (!shellApiBase) throw new Error('Shell API base URL is not configured')\n  return shellApiBase\n}\n\nasync function invoke(channel: string, ...args: unknown[]) {\n  const apiBase = getShellApiBase()\n  const headers: Record<string, string> = { 'Content-Type': 'application/json' }\n  if (shellApiToken) headers['X-TaskWeaver-Shell-Token'] = shellApiToken\n  const response = await fetch(\`\${apiBase}/shell/v1/invoke\`, {\n    method: 'POST',\n    headers,\n    body: JSON.stringify({ channel, args }),\n  })\n  const body = await response.json() as { ok?: boolean; data?: unknown; error?: string }\n  if (!response.ok) {\n    throw new Error(body.error || \`Shell invoke failed (\${channel})\`)\n  }\n  return body\n}\n\nexport function createShellTaskweaverBridge(): TaskweaverBridge {\n  return ${renderObject(tree, 2)} as TaskweaverBridge\n}\n`
}

const next = renderShellBridge()

export function checkGeneratedShellBridge() {
  const prev = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : ''
  return prev === next
}

if (process.argv.includes('--check')) {
  if (!checkGeneratedShellBridge()) {
    console.error('gen-shell-bridge: stale; run node scripts/gen-shell-bridge.mjs')
    process.exit(1)
  }
  console.log('gen-shell-bridge: up to date')
} else if (path.resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(path.dirname(outPath), { recursive: true })
  fs.writeFileSync(outPath, next)
  console.log('gen-shell-bridge: wrote src/shell/taskweaver-shell-bridge.generated.ts')
}
