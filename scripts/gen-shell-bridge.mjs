#!/usr/bin/env node
/** Generate renderer HTTP bridge for native shells (Swift / future WebView2). */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { IPC_CHANNELS, PRELOAD_EVENTS, PRELOAD_LOCAL_METHODS } from '../contract/channels.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outPath = path.join(root, 'src/shell/taskweaver-shell-bridge.generated.ts')

function setBridgeMethod(tree, bridgePath, source) {
  const segments = bridgePath.split('.')
  let current = tree
  for (const segment of segments.slice(0, -1)) {
    if (current[segment] === undefined) current[segment] = {}
    current = current[segment]
  }
  current[segments.at(-1)] = source
}

function renderObject(tree, indent = 2) {
  const pad = ' '.repeat(indent)
  const childPad = ' '.repeat(indent + 2)
  const lines = Object.entries(tree).map(([key, value]) => {
    const rendered = typeof value === 'string' ? value : renderObject(value, indent + 2)
    return `${childPad}${key}: ${rendered}`
  })
  return `{\n${lines.join(',\n')}\n${pad}}`
}

function renderShellBridge() {
  const tree = {}
  for (const entry of IPC_CHANNELS) {
    setBridgeMethod(tree, entry.bridgePath, `(...args: unknown[]) => invoke(${JSON.stringify(entry.name)}, ...args)`)
  }
  for (const entry of PRELOAD_EVENTS) {
    const sub = `(listener: (payload: unknown) => void) => subscribe(${JSON.stringify(entry.event)}, listener)`
    setBridgeMethod(tree, entry.bridgePath, sub)
  }
  for (const entry of PRELOAD_LOCAL_METHODS) {
    if (entry.bridgePath === 'workspace.getDroppedFilePath') {
      setBridgeMethod(tree, entry.bridgePath, '(_file: File) => ""')
      continue
    }
    setBridgeMethod(tree, entry.bridgePath, '() => undefined')
  }

  return `// AUTO-GENERATED by scripts/gen-shell-bridge.mjs — 勿手改。\n\nimport type { TaskweaverBridge } from '../shared/ipc-bridge.generated'\n\nlet eventSource: EventSource | null = null\nconst channelListeners = new Map<string, Set<(payload: unknown) => void>>()\n\nfunction ensureEventSource(apiBase: string) {\n  if (eventSource) return eventSource\n  eventSource = new EventSource(\`\${apiBase}/shell/v1/events\`)\n  eventSource.addEventListener('message', (event) => {\n    try {\n      const parsed = JSON.parse(String(event.data)) as { channel?: string; payload?: unknown }\n      if (!parsed.channel) return\n      const listeners = channelListeners.get(parsed.channel)\n      if (!listeners) return\n      for (const listener of listeners) listener(parsed.payload)\n    } catch {\n      /* ignore malformed push */\n    }\n  })\n  return eventSource\n}\n\nfunction subscribe(channel: string, listener: (payload: unknown) => void) {\n  const apiBase = getShellApiBase()\n  ensureEventSource(apiBase)\n  let set = channelListeners.get(channel)\n  if (!set) {\n    set = new Set()\n    channelListeners.set(channel, set)\n  }\n  set.add(listener)\n  return () => {\n    set?.delete(listener)\n  }\n}\n\nlet shellApiBase: string | null = null\n\nexport function setShellApiBase(base: string) {\n  shellApiBase = base.replace(/\\/$/, '')\n}\n\nexport function getShellApiBase() {\n  if (!shellApiBase) throw new Error('Shell API base URL is not configured')\n  return shellApiBase\n}\n\nasync function invoke(channel: string, ...args: unknown[]) {\n  const apiBase = getShellApiBase()\n  const response = await fetch(\`\${apiBase}/shell/v1/invoke\`, {\n    method: 'POST',\n    headers: { 'Content-Type': 'application/json' },\n    body: JSON.stringify({ channel, args }),\n  })\n  const body = await response.json() as { ok?: boolean; data?: unknown; error?: string }\n  if (!response.ok || body.ok === false) {\n    throw new Error(body.error || \`Shell invoke failed (\${channel})\`)\n  }\n  return body.data\n}\n\nexport function createShellTaskweaverBridge(): TaskweaverBridge {\n  return ${renderObject(tree, 2)} as TaskweaverBridge\n}\n`
}

const next = renderShellBridge()

export function checkGeneratedShellBridge() {
  const prev = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : ''
  return prev === next
}

if (process.argv.includes('--check')) {
  if (!checkGeneratedShellBridge()) {
    console.error('gen-shell-bridge: stale; run node scripts/gen-shell-bridge.mjs')
    process.exit(1)
  }
  console.log('gen-shell-bridge: up to date')
} else if (path.resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(path.dirname(outPath), { recursive: true })
  fs.writeFileSync(outPath, next)
  console.log('gen-shell-bridge: wrote src/shell/taskweaver-shell-bridge.generated.ts')
}
